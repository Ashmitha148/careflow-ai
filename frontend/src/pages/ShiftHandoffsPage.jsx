import { useState, useEffect, useRef, useCallback } from "react";
import { ArrowRightLeft, Users, Clock, FileText, Sparkles, AlertTriangle } from "lucide-react";
import { useAuth } from "../context/AuthContext";
import { useSocket } from "../context/SocketContext";
import api from "../services/api";
import { getMyPatients } from "../services/patientApi";
import { WS_CHANNELS } from "../services/websocket/realtimeChannels";

const AI_POLL_INTERVAL_MS = 2000;
const AI_POLL_MAX_MS = 60000;

export default function ShiftHandoffsPage() {
  const { user } = useAuth();
  const { subscribe } = useSocket();
  const [patients, setPatients] = useState([]);
  const [nurses, setNurses] = useState([]);
  const [selectedPatientId, setSelectedPatientId] = useState("");
  const [toNurseId, setToNurseId] = useState("");
  const [handoffs, setHandoffs] = useState([]);
  const [loading, setLoading] = useState(true);
  const [creating, setCreating] = useState(false);
  const [createError, setCreateError] = useState("");
  const [notes, setNotes] = useState("");
  const pollTimersRef = useRef([]);

  useEffect(() => {
    getMyPatients()
      .then((data) => {
        setPatients(data || []);
        if (data?.length === 1) setSelectedPatientId(data[0].id);
      })
      .catch(() => setPatients([]))
      .finally(() => setLoading(false));
    api
      .get("/shift-handoffs/nurses")
      .then((res) => {
        const options = (res.data || []).filter((n) => n.id !== user?.id);
        setNurses(options);
        if (options.length === 1) setToNurseId(options[0].id);
      })
      .catch(() => setNurses([]));
  }, [user?.id]);

  const refreshHandoffs = useCallback((patientId) => {
    if (!patientId) return;
    api
      .get(`/shift-handoffs/patient/${patientId}`)
      .then((res) => setHandoffs(res.data || []))
      .catch(() => setHandoffs([]));
  }, []);

  useEffect(() => {
    refreshHandoffs(selectedPatientId);
  }, [selectedPatientId, refreshHandoffs]);

  // Phase 2 realtime: the AI summary is generated by the outbox worker and
  // pushed on /topic/patient/{id}/handoffs — refresh the list on arrival.
  useEffect(() => {
    if (!selectedPatientId) return undefined;
    return subscribe(WS_CHANNELS.handoffs(selectedPatientId), () =>
      refreshHandoffs(selectedPatientId),
    );
  }, [selectedPatientId, subscribe, refreshHandoffs]);

  useEffect(() => () => {
    pollTimersRef.current.forEach(clearTimeout);
  }, []);

  /**
   * POST returns 202 (aiStatus PENDING) — the summary arrives asynchronously.
   * Primary delivery is the WebSocket topic above; this poll of
   * GET /shift-handoffs/{id} is the fallback for clients that missed it.
   */
  const pollUntilAiSettles = useCallback(
    (handoffId, patientId) => {
      const startedAt = Date.now();
      const tick = () => {
        api
          .get(`/shift-handoffs/${handoffId}`)
          .then((res) => {
            const status = res.data?.aiStatus;
            setHandoffs((old) =>
              old.map((h) => (h.id === handoffId ? { ...h, ...res.data } : h)),
            );
            if (status === "DONE" || status === "FAILED") return;
            if (Date.now() - startedAt > AI_POLL_MAX_MS) return;
            const timer = setTimeout(tick, AI_POLL_INTERVAL_MS);
            pollTimersRef.current.push(timer);
          })
          .catch(() => {});
      };
      const timer = setTimeout(tick, AI_POLL_INTERVAL_MS);
      pollTimersRef.current.push(timer);
      void patientId;
    },
    [],
  );

  const createHandoff = useCallback(async () => {
    if (!selectedPatientId || !toNurseId) return;
    setCreating(true);
    setCreateError("");
    try {
      const res = await api.post("/shift-handoffs", null, {
        params: {
          patientId: selectedPatientId,
          fromNurseId: user.id,
          toNurseId,
          notes,
          shiftDate: new Date().toISOString().slice(0, 10),
        },
      });
      // 202 Accepted: the handoff row exists; the AI summary is pending.
      setHandoffs((old) => [res.data, ...old]);
      setNotes("");
      pollUntilAiSettles(res.data.id, selectedPatientId);
    } catch (err) {
      setCreateError(
        err?.response?.data?.message || "Could not create the handoff. Try again.",
      );
    } finally {
      setCreating(false);
    }
  }, [selectedPatientId, toNurseId, user?.id, notes, pollUntilAiSettles]);

  const selectedPatient = patients.find((p) => p.id === selectedPatientId);

  return (
    <div className="space-y-6 pb-10">
      <div>
        <p className="text-xs font-medium text-teal-400">Care transitions</p>
        <h1 className="mt-1 text-xl font-semibold">Shift handoffs</h1>
        <p className="mt-1 text-xs text-[var(--text-muted)]">
          Transfer patient care between shifts and teams
        </p>
      </div>

      {patients.length > 1 && (
        <div className="surface rounded-2xl p-4">
          <div className="flex items-center gap-2">
            <Users className="h-4 w-4 text-[var(--text-muted)]" />
            <select
              value={selectedPatientId}
              onChange={(e) => setSelectedPatientId(e.target.value)}
              className="h-10 rounded-xl border border-[var(--border-color)] bg-[var(--bg-subtle)] px-3 text-xs text-[var(--text-primary)] outline-none focus:border-teal-500/50"
            >
              <option value="">Select a patient for handoff</option>
              {patients.map((p) => (
                <option key={p.id} value={p.id}>
                  {p.name} — {p.mrn}
                </option>
              ))}
            </select>
          </div>
        </div>
      )}

      {loading && (
        <div className="surface rounded-2xl p-8 text-center text-sm text-[var(--text-muted)]">
          Loading...
        </div>
      )}

      {!loading && selectedPatient && (
        <div className="space-y-4">
          <div className="surface rounded-2xl p-5">
            <div className="flex items-center gap-3 mb-4">
              <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-teal-500/10 text-teal-400">
                <ArrowRightLeft className="h-5 w-5" />
              </div>
              <div>
                <p className="text-sm font-medium">{selectedPatient.name}</p>
                <p className="text-xs text-[var(--text-muted)]">{selectedPatient.mrn}</p>
              </div>
            </div>

            <div className="space-y-3">
              <div>
                <label className="text-xs font-medium text-[var(--text-muted)]">Handoff notes</label>
                <textarea
                  value={notes}
                  onChange={(e) => setNotes(e.target.value)}
                  placeholder="Enter handoff notes for the next shift..."
                  className="mt-1 h-24 w-full rounded-xl border border-[var(--border-color)] bg-[var(--bg-subtle)] p-3 text-xs text-[var(--text-primary)] outline-none focus:border-teal-500/50 resize-none"
                />
              </div>

              <div className="flex justify-end">
                <button
                  type="button"
                  className="rounded-xl bg-teal-500 px-4 py-2 text-xs font-semibold text-slate-950 hover:bg-teal-400 transition"
                >
                  Create handoff
                </button>
              </div>
            </div>
          </div>

          {handoffs.length > 0 && (
            <div className="space-y-3">
              <h3 className="text-sm font-semibold">Previous handoffs</h3>
              {handoffs.map((h) => (
                <div key={h.id} className="surface rounded-2xl p-4">
                  <div className="flex items-center gap-2 text-[var(--text-muted)] mb-2">
                    <Clock className="h-3 w-3" />
                    <span className="text-[10px]">{new Date(h.shiftDate).toLocaleDateString()}</span>
                  </div>
                  <p className="text-xs">{h.notes}</p>
                  {h.aiSummary && (
                    <div className="mt-2 rounded-lg bg-teal-500/5 px-3 py-2">
                      <p className="text-[10px] text-teal-400 font-medium">AI Summary</p>
                      <p className="text-[11px] text-[var(--text-muted)] mt-0.5">{h.aiSummary}</p>
                    </div>
                  )}
                </div>
              ))}
            </div>
          )}
        </div>
      )}

      {!loading && !selectedPatientId && patients.length > 0 && (
        <div className="surface rounded-2xl p-8 text-center">
          <ArrowRightLeft className="mx-auto h-8 w-8 text-[var(--text-muted)]" />
          <p className="mt-3 text-sm font-medium">Select a patient to create a handoff</p>
        </div>
      )}
    </div>
  );
}